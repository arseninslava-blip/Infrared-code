// ПОДБИРАЕТСЯ ОПЫТНЫМ ПУТЁМ (реальной калибровки нет). Одометрия по колёсам
// даёт скорость робота в тех же условных "wheel dps", что wheelSpeed в
// omniMoveDirection; скорость мяча с камеры - в единицах ball_dist/сек. Это
// разные шкалы, точный переводной коэффициент неизвестен -
// ROBOT_VEL_UNIT_SCALE переводит одометрию в шкалу камеры перед сложением.
// Калибровка на роботе: покатить мяч с известной скоростью мимо НЕПОДВИЖНОГО
// робота, посмотреть печатаемую скорость мяча; затем катить сам робот с
// известной скоростью на НЕПОДВИЖНЫЙ мяч и подогнать константу так, чтобы
// оценка скорости совпадала в обоих случаях.
// ВРЕМЕННО 0 (было 1.0): при 1.0 неоткалиброванная одометрия давала
// огромную ложную скорость мяча (~950-1000 ед/с) на НЕПОДВИЖНОМ мяче,
// стоило роботу чуть покачаться на месте (w в стойке ожидания) - похоже,
// шкала "wheel dps" на 1-2 порядка больше шкалы камеры, и без калибровки
// компенсация только вредит. 0 = скорость мяча считается БЕЗ вычета
// собственного движения робота (менее точно при реальном движении робота,
