// Кадр камеры считаем "новым" не чаще, чем раз в столько мс (иначе на почти
// нулевом dt скорость улетает в мусор при дребезге/повторной выдаче кадра).
// Чем меньше - тем чаще обновление, но и тем сильнее шум/дискретность камеры
// усиливается делением на маленький dt.
#define BALLVEL_MIN_DT_MS      40
// Если реально новых кадров камеры нет дольше этого - считаем скорость мяча
// неизвестной (мяч потерян из вида, экстраполировать нечего)
#define BALLVEL_STALE_MS       400
// Сглаживание (экспоненциальное) скорости мяча: 0..1, доля НОВОГО измерения
// в оценке на каждом обновлении. Меньше - плавнее, но медленнее реагирует на
// реальное изменение скорости; больше - быстрее реагирует, но шумнее.
#define BALLVEL_EMA_ALPHA      0.25f
// Мяч лежит на месте (или почти) - оценка скорости всё равно не даёт ровно
// 0 из-за шума камеры/одометрии. Всё, что медленнее этого (ед.камеры/с),
// считаем шумом и обнуляем - иначе случайный знак шума врубает перехват
// (towardGate2 в defense2() может стать >0 без реального движения мяча).
// ПОДБИРАЕТСЯ ОПЫТНЫМ ПУТЁМ: положить мяч неподвижно, посмотреть в выводе
