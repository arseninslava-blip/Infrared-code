// dir/dist на кадр-два, видно по резким скачкам bx/by в логе). Если по
// сырой (несглаженной) разнице получается скорость больше этого
// (ед.камеры/с) - считаем кадр глюком и просто игнорируем его целиком
// (не трогаем ballVelX/Y и prevWorld/lastSample), а не подмешиваем в оценку.
#define BALLVEL_MAX_PLAUSIBLE  500.0f

// Перехватываем только если мяч ближе этого (в "единицах" ball_dist камеры,
// не мм - см. ROBOT_VEL_UNIT_SCALE ниже). Направление проверяется отдельно
// в defense2() - перехват идёт при ЛЮБОЙ скорости мяча в сторону ворот 2.
#define INTERCEPT_RANGE        60
// На сколько секунд вперёд экстраполируем положение мяча для точки перехвата
#define INTERCEPT_LOOKAHEAD_S  0.35f
// На практике мяч почти всегда близко (INTERCEPT_RANGE=60), а старый
// GAIN=15 давал dist*GAIN < MIN почти всегда - скорость перехвата была
// ВСЕГДА прижата к минимуму независимо от реальной срочности (видно в логе:
// v=1200 в каждой строке с intercept=1). Подняли MIN и GAIN, чтобы скорость
// реально росла с расстоянием до точки перехвата в этом диапазоне дистанций.
#define INTERCEPT_SPEED_MIN    1800
#define INTERCEPT_SPEED_MAX    3200
// скорость выезда в точку перехвата = дистанция_до_неё(ед.камеры) * это
#define INTERCEPT_SPEED_GAIN   40.0f
// Флаг перехвата держится true ещё столько мс после последнего "да" - гасит
// дребезг intercepting туда-обратно на резко/шумно движущемся мяче.
#define DEF2_INTERCEPT_HOLD_MS 150

