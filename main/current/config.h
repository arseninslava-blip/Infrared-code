//  Езда по координатам поля (navigation.h, driveTo)
// ============================================================================

#define GOTO_SPEED_MAX       4000  // скорость вдали от точки (≈ 2 м/с по логу)
#define GOTO_SPEED_MIN       150   // ниже этого робот не трогается с места
