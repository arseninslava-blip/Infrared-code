// Сколько единиц скорости набирается за 1 секунду. Линейная рампа (постоянное
// ускорение) -> график speed(t) прямая линия, не мгновенный скачок (90°) и не
// пологая кривая. Наклон задан углом 75° на графике, где по горизонтали 1
// секунда соответствует по высоте MAX_MOTOR_SPEED:
//   MOTOR_ACCEL_PER_SEC = MAX_MOTOR_SPEED * tan(75°) ≈ 2000 * 3.732 ≈ 7464
// т.е. разгон с 0 до MAX_MOTOR_SPEED занимает ~0.27с.
#define MOTOR_ACCEL_PER_SEC 7464.0f

